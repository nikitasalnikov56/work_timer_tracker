/// Выполняет асинхронные операции строго по очереди.
///
/// Без этого два быстрых нажатия «Старт» запускали бы две проверки
/// «нет ли активного таймера» одновременно, обе видели бы «нет»,
/// и у сотрудника появлялись бы два параллельных таймера.
class SerialExecutor {
  Future<void> _tail = Future<void>.value();

  Future<T> run<T>(Future<T> Function() action) {
    final result = _tail.then((_) => action());
    // Ошибка одной операции не должна блокировать следующие:
    // вызывающий код получает её через [result], а очередь идёт дальше.
    _tail = result.then<void>((_) {}, onError: (Object _) {});
    return result;
  }
}
